export const dictionaries = { nl, en };
export type Dictionary = typeof nl;
export const LanguageContext = createContext<{
  locale: Locale;
  t: Dictionary;
  setLocale: (locale: Locale) => void;
}>({ locale: 'nl', t: nl, setLocale: () => {} });
export const useLanguage = () => useContext(LanguageContext);
export function errorText(error: unknown, t: Dictionary): string {
  if (!(error instanceof ApiError)) return t.genericError;
  if (error.status === 0) return t.networkError;
  if (error.status === 401) return t.unauthorized;
  if (error.status === 403) return t.forbidden;
  if (error.status === 404) return t.notFound;
  if (error.status === 409) return t.conflict;
  if (error.status === 413) return t.tooLarge;
  if (error.status === 429) return t.rateLimited;
  if (error.status === 400 || error.status === 422) return t.invalidInput;
  if (error.status >= 500) return t.serverError;
  return t.genericError;
}
